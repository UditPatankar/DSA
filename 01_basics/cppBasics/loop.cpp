#include<bits/stdc++.h>
using namespace std;

int main() {
   for(int i = 0; i < 50; i++) {
      cout << "Hello World!" << endl;
   }

   int i = 0;
   while(i < 10) {
      cout << i << endl;
      i++;
   }

   int j = 0;
   do{
      cout << j << endl;
      j++;
   } while(j < 10);

   return 0;
}